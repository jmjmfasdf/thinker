def fit_binary_run(
    frame: pd.DataFrame,
    outcome: str,
    predictors: Sequence[str],
    categorical: Optional[str] = None,
) -> Tuple[Dict[str, float], int, int]:
    columns = [outcome] + list(predictors) + ([categorical] if categorical else [])
    data = frame[columns].replace([np.inf, -np.inf], np.nan).dropna().copy()
    data = data.loc[pd.to_numeric(data[outcome], errors="coerce").isin((0, 1))].copy()
    if len(data) < 80:
        return {}, len(data), 0
    events = int(pd.to_numeric(data[outcome], errors="coerce").sum())
    if events < 5 or events > len(data) - 5:
        return {}, len(data), events
    design = pd.DataFrame(index=data.index)
    for predictor in predictors:
        design[predictor] = standardize(data[predictor])
    if categorical:
        dummies = pd.get_dummies(
            data[categorical].astype(int).astype(str),
            prefix=categorical,
            drop_first=True,
            dtype=float,
        )
        design = pd.concat([design, dummies], axis=1)
    design = sm.add_constant(design, has_constant="add")
    try:
        model = sm.GLM(
            data[outcome].astype(float),
            design.astype(float),
            family=sm.families.Binomial(),
        )
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always", PerfectSeparationWarning)
            fit = model.fit(maxiter=150, disp=0)
        separated = any(
            issubclass(item.category, PerfectSeparationWarning) for item in caught
        )
        params = pd.Series(np.asarray(fit.params, dtype=float), index=design.columns)
        if separated or not np.all(np.isfinite(params.to_numpy())):
            fit = model.fit_regularized(alpha=1e-6, L1_wt=0.0, maxiter=150)
            params = pd.Series(np.asarray(fit.params, dtype=float), index=design.columns)
    except Exception:
        return {}, len(data), events
    return {name: float(params.get(name, np.nan)) for name in predictors}, len(data), events


def fit_linear_run(
    frame: pd.DataFrame,
    outcome: str,
    predictors: Sequence[str],
    categorical: Optional[str] = None,
) -> Tuple[Dict[str, float], int]:
    columns = [outcome] + list(predictors) + ([categorical] if categorical else [])
    data = frame[columns].replace([np.inf, -np.inf], np.nan).dropna().copy()
    if len(data) < max(40, 5 * len(predictors)):
        return {}, len(data)
    design = pd.DataFrame(index=data.index)
    for predictor in predictors:
        design[predictor] = standardize(data[predictor])
    if categorical:
        dummies = pd.get_dummies(
            data[categorical].astype(int).astype(str),
            prefix=categorical,
            drop_first=True,
            dtype=float,
        )
        design = pd.concat([design, dummies], axis=1)
    design = sm.add_constant(design, has_constant="add")
    try:
        fit = sm.OLS(standardize(data[outcome]).astype(float), design.astype(float)).fit()
    except Exception:
        return {}, len(data)
    return {name: float(fit.params.get(name, np.nan)) for name in predictors}, len(data)


def selected_minus_other(matrix: np.ndarray, choices: np.ndarray) -> np.ndarray:
    output = np.full(len(choices), np.nan, dtype=float)
    for row_index, choice in enumerate(choices):
        if choice < 0 or choice >= matrix.shape[1] or not np.isfinite(matrix[row_index, choice]):
            continue
        alternatives = np.delete(matrix[row_index], choice)
        alternatives = alternatives[np.isfinite(alternatives)]
        if len(alternatives):
            output[row_index] = matrix[row_index, choice] - float(np.mean(alternatives))
    return output


def probabilities_to_margin(probabilities: np.ndarray, choices: np.ndarray) -> np.ndarray:
    output = np.full(len(choices), np.nan, dtype=float)
    for index, choice in enumerate(choices):
        if choice < 0 or choice >= probabilities.shape[1]:
            continue
        row = probabilities[index]
        if not np.all(np.isfinite(row)):
            continue
        other = np.max(np.delete(row, choice))
        output[index] = math.log(max(row[choice], EPS)) - math.log(max(other, EPS))
    return output


def load_subject_cache(subject: int, game: int, cache_root: Path):
    global N_ACTIONS
    paths = cache_paths(cache_root, subject, game)
    manifest = validate_manifest(paths, subject=subject, game=game)
    N_ACTIONS = int(manifest.get("num_actions", manifest.get("n_actions", 6)))
    window_columns = KEYS + [
        "subject", "game", "real_step_id", "incumbent_action", "human_action",
        "switch", "persistence_evidence", "switch_target_uncertainty",
        "value_revision_event_fraction", "n_status2",
        "root_value", "mean_bout_terminal_depth", "deep_event_fraction",
    ]
    windows = read_columns(paths.persistence_windows, window_columns)
    for action in range(N_ACTIONS):
        extra = read_columns(
            paths.persistence_windows,
            KEYS + [
                f"root_q_initial_{action}", f"root_q_final_{action}",
                f"root_n_initial_{action}", f"root_n_final_{action}",
            ],
        )
        windows = windows.merge(extra, on=KEYS, how="left", validate="one_to_one")
    model_columns = KEYS + [
        "bout_age", "prior_reward", "prior_done", "run_progress",
        "model_candidate", "actor_initial_candidate",
        "initial_actor_policy_complete", "terminal_actor_policy_complete",
    ]
    for action in range(N_ACTIONS):
        model_columns += [
            f"model_root_p_{action}", f"actor_initial_p_{action}",
            f"actor_terminal_p_{action}",
        ]
    model = read_columns(paths.model_control_windows, model_columns)
    actor = read_columns(paths.actor_metrics, KEYS + ["thinker_action"])
    windows = windows.merge(model, on=KEYS, how="inner", validate="one_to_one")
    windows = windows.merge(actor, on=KEYS, how="left", validate="one_to_one")
    bouts = read_columns(
        paths.persistence_bouts,
        KEYS + [
            "bout_index", "first_status2_position", "terminal_status2_position",
            "reset_known", "branch", "terminal_depth", "terminal_rollout_return",
        ],
    )
    events = read_columns(
        paths.persistence_events,
        KEYS + [
            "bout_index", "status2_position", "depth", "branch", "rollout_return",
            "return_gain_from_root", "root_q_before_sampled", "root_q_after_sampled",
            "root_n_before_sampled", "root_n_after_sampled", "root_q_revision",
            "rollout_prediction_error", "directed_value_revision",
            "directed_prediction_error", "value_revision_valid",
        ],
    )
    # A native RESET-to-root computation has no action branch. Its budget is
    # retained in windows; action-level effects require a branch-bearing event.
    events = events.loc[events["branch"].between(0, N_ACTIONS-1)].copy()
    rollout_keys = read_columns(paths.rollout_windows, KEYS).reset_index(names="window_index")
    if rollout_keys.duplicated(KEYS).any():
        raise RuntimeError("rollout windows are not one-to-one")
    prefix_columns = [
        "window_index", "event_index", "return_advantage", "event_progress",
        "same_branch_next", "branch_switch_next", "same_path_deepen_next",
        "reset_after", "pair_valid",
    ]
    with np.load(paths.rollout_prefix_events, allow_pickle=False) as archive:
        missing_prefix = [name for name in prefix_columns if name not in archive.files]
        if missing_prefix:
            raise KeyError(f"prefix cache lacks {missing_prefix}")
        prefix = {name: archive[name] for name in prefix_columns}
    return paths, manifest, windows, bouts, events, rollout_keys, prefix


def attach_prefix_pairs(
    events: pd.DataFrame,
    windows: pd.DataFrame,
    rollout_keys: pd.DataFrame,
    prefix: Mapping[str, np.ndarray],
) -> pd.DataFrame:
    pair_names = [
        "return_advantage", "event_progress", "same_branch_next",
        "branch_switch_next", "same_path_deepen_next", "reset_after", "pair_valid",
    ]
    required = {"window_index", "event_index", *pair_names}
    missing = required.difference(prefix)
    if missing:
        raise KeyError(f"prefix cache lacks {sorted(missing)}")
    prefix_frame = pd.DataFrame({name: np.asarray(prefix[name]) for name in required})
    pairs = events.loc[pd.to_numeric(events["branch"], errors="coerce").between(0, N_ACTIONS-1)].copy()
    pairs = pairs.merge(rollout_keys, on=KEYS, how="left", validate="many_to_one")
    if pairs["window_index"].isna().any():
        raise RuntimeError("persistence events do not align with rollout windows")
    pairs = pairs.merge(prefix_frame.rename(columns={"event_index": "status2_position"}),
                        on=["window_index", "status2_position"], how="inner", validate="one_to_one")
    metadata = windows[KEYS + [
        "subject", "game", "incumbent_action", "human_action", "thinker_action",
        "persistence_evidence", "switch_target_uncertainty", "bout_age",
        "prior_reward", "prior_done", "run_progress", "n_status2",
    ] + [f"model_root_p_{action}" for action in range(N_ACTIONS)]]
    pairs = pairs.merge(metadata, on=KEYS, how="left", validate="many_to_one")
    pairs = pairs.loc[(pairs["status2_position"] + 1 < pairs["n_status2"])
                      & pairs["pair_valid"].eq(1)].copy()
    branch = pairs["branch"].to_numpy(dtype=int)
    prior = pairs[[f"model_root_p_{action}" for action in range(N_ACTIONS)]].to_numpy(dtype=float)
    pairs["model_prior_branch"] = prior[np.arange(len(pairs)), branch]
    pairs["absolute_q_revision"] = np.abs(pd.to_numeric(pairs["root_q_revision"], errors="coerce"))
    pairs["absolute_prediction_error"] = np.abs(
        pd.to_numeric(pairs["rollout_prediction_error"], errors="coerce")
    )
    # The native adapter decodes log1p counts and supplies this legacy fraction.
    rec_t = pd.to_numeric(pairs["n_status2"], errors="coerce").fillna(0) + 1.0
    pairs["root_n_before_count"] = (
        pd.to_numeric(pairs["root_n_before_sampled"], errors="coerce").clip(lower=0) * rec_t
    )
    pairs["log_prior_visits"] = np.log1p(pairs["root_n_before_count"])
    pairs["first_visit"] = pairs["root_n_before_count"].le(EPS).astype(int)
    pairs["positive_rollout_gain"] = pd.to_numeric(
        pairs["return_advantage"], errors="coerce"
    ).clip(lower=0)
    pairs["action_relevance"] = pd.to_numeric(pairs["model_prior_branch"], errors="coerce")
    pairs["predicted_update_scale"] = pairs["absolute_prediction_error"] / (
        1.0 + pairs["root_n_before_count"]
    )
    return pairs


def reset_choice_contrasts(
    events: pd.DataFrame,
    windows: pd.DataFrame,
) -> pd.DataFrame:
    lookup = windows.set_index(KEYS)
    records: List[Dict[str, object]] = []
    ordered = events.sort_values(KEYS + ["status2_position"], kind="stable")
    for key, source in ordered.groupby(KEYS, sort=False, observed=True):
        if key not in lookup.index:
            continue
        row = lookup.loc[key]
        q = np.asarray([row[f"root_q_initial_{a}"] for a in range(N_ACTIONS)], dtype=float)
        n = np.asarray([row[f"root_n_initial_{a}"] for a in range(N_ACTIONS)], dtype=float)
        prior = np.asarray([row[f"model_root_p_{a}"] for a in range(N_ACTIONS)], dtype=float)
        return_sum = np.zeros(N_ACTIONS, dtype=float)
        return_count = np.zeros(N_ACTIONS, dtype=float)
        previous_bout = None
        previous_branch = None
        for event in source.itertuples(index=False):
            bout = int(event.bout_index)
            branch = int(event.branch)
            if previous_bout is not None and bout != previous_bout:
                q_contrast = selected_minus_other(q[None, :], np.asarray([branch]))[0]
                n_contrast = selected_minus_other(n[None, :], np.asarray([branch]))[0]
                prior_contrast = selected_minus_other(prior[None, :], np.asarray([branch]))[0]
                means = np.divide(
                    return_sum, return_count,
                    out=np.full(N_ACTIONS, np.nan), where=return_count > 0,
                )
                return_contrast = selected_minus_other(means[None, :], np.asarray([branch]))[0]
                records.append(
                    {
                        "run_label": key[0], "real_step": key[1],
                        "next_bout_index": bout, "chosen_branch": branch,
                        "previous_branch": previous_branch,
                        "same_branch_choice": int(branch == previous_branch),
                        "q_contrast": q_contrast, "visit_contrast": n_contrast,
                        "model_prior_contrast": prior_contrast,
                        "prior_return_contrast": return_contrast,
                    }
                )
            q_after = float(event.root_q_after_sampled)
            n_after = float(event.root_n_after_sampled)
            if np.isfinite(q_after):
                q[branch] = q_after
            if np.isfinite(n_after):
                n[branch] = n_after
            value = float(event.rollout_return)
            if np.isfinite(value):
                return_sum[branch] += value
                return_count[branch] += 1
            previous_bout = bout
            previous_branch = branch
    return pd.DataFrame(records)


def terminal_branch_matrices(
    events: pd.DataFrame,
    windows: pd.DataFrame,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    base = windows[KEYS].reset_index(drop=True).reset_index(names="window_index")
    grouped = (
        events.groupby(KEYS + ["branch"], sort=False, observed=True)["rollout_return"]
        .agg(["mean", "max", "count"]).reset_index()
        .merge(base, on=KEYS, how="left", validate="many_to_one")
    )
    matrices = [np.full((len(base), N_ACTIONS), np.nan, dtype=float) for _ in range(3)]
    wi = grouped["window_index"].to_numpy(dtype=int)
    branch = grouped["branch"].to_numpy(dtype=int)
    for matrix, name in zip(matrices, ("mean", "max", "count")):
        matrix[wi, branch] = pd.to_numeric(grouped[name], errors="coerce").to_numpy(dtype=float)
    matrices[2] = np.nan_to_num(matrices[2], nan=0.0)
    return tuple(matrices)  # type: ignore[return-value]


def fit_conditional_logit(
    feature_matrices: Mapping[str, np.ndarray], choices: np.ndarray, mask: np.ndarray,
) -> Tuple[Dict[str, float], int]:
    """Six-alternative conditional logit with action intercepts."""
    names = list(feature_matrices)
    x = np.stack([feature_matrices[name][mask] for name in names], axis=2).astype(float)
    y = choices[mask].astype(int)
    valid = (y >= 0) & (y < N_ACTIONS) & np.all(np.isfinite(x), axis=(1, 2))
    x, y = x[valid], y[valid]
    if len(y) < 100 or len(np.unique(y)) < 2:
        return {}, len(y)
    for column in range(x.shape[2]):
        values = x[:, :, column]
        scale = float(values.std())
        x[:, :, column] = (values - float(values.mean())) / scale if scale > EPS else 0.0
    action_fixed = np.broadcast_to(np.eye(N_ACTIONS)[None, :, 1:], (len(x), N_ACTIONS, N_ACTIONS - 1))
    design = np.concatenate([x, action_fixed], axis=2)
    rows = np.arange(len(y))
    def objective(beta: np.ndarray):
        eta = np.einsum("nap,p->na", design, beta)
        probability = np.exp(eta - logsumexp(eta, axis=1, keepdims=True))
        loss = -float(np.sum(eta[rows, y] - logsumexp(eta, axis=1)))
        chosen = design[rows, y]
        expected = np.einsum("na,nap->np", probability, design)
        gradient = -np.sum(chosen - expected, axis=0)
        return loss, gradient
    fit = minimize(objective, np.zeros(design.shape[2]), jac=True, method="L-BFGS-B")
    if not fit.success:
        return {}, len(y)
    return {name: float(fit.x[index]) for index, name in enumerate(names)}, len(y)


def normalize_policy_rows(matrix: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    """Normalize complete non-negative policy rows and return a validity mask."""
    values = np.asarray(matrix, dtype=float)
    total = np.sum(values, axis=1)
    valid = np.all(np.isfinite(values), axis=1) & np.all(values >= 0, axis=1) & (total > EPS)
    output = np.full_like(values, np.nan)
    output[valid] = values[valid] / total[valid, None]
    return output, valid


def make_readout_features(
    windows: pd.DataFrame,
    events: pd.DataFrame,
) -> Tuple[Dict[str, np.ndarray], np.ndarray, np.ndarray, np.ndarray, pd.DataFrame]:
    """Construct action-specific terminal search summaries without future actions."""
    mean_return, max_return, event_visits = terminal_branch_matrices(events, windows)
    final_q = windows[[f"root_q_final_{a}" for a in range(N_ACTIONS)]].to_numpy(dtype=float)
    final_n = windows[[f"root_n_final_{a}" for a in range(N_ACTIONS)]].to_numpy(dtype=float)
    prior = windows[[f"model_root_p_{a}" for a in range(N_ACTIONS)]].to_numpy(dtype=float)
    target_raw = windows[[f"actor_terminal_p_{a}" for a in range(N_ACTIONS)]].to_numpy(dtype=float)
    prior, prior_valid = normalize_policy_rows(prior)
    target, target_valid = normalize_policy_rows(target_raw)
    visited = ((event_visits > 0) | (np.nan_to_num(final_n, nan=0.0) > 0)).astype(float)
    # event_visits is a true count. root_n_final is a normalized share and is
    # intentionally not mixed into this scale; it is used only to establish
    # whether a terminal branch is represented.
    visits = event_visits
    root = pd.to_numeric(windows["root_value"], errors="coerce").to_numpy(dtype=float)[:, None]
    features = {
        "log_model_prior": np.log(np.clip(prior, EPS, 1.0)),
        # Keep all game actions in every choice set. Missing branch summaries
        # denote an unvisited branch and are coded as zero jointly with the
        # explicit branch_visited indicator rather than deleting that action.
        "terminal_root_q": np.nan_to_num(final_q, nan=0.0),
        "terminal_mean_rollout_gain": np.where(
            np.isfinite(mean_return), mean_return - root, 0.0
        ),
        "terminal_max_rollout_gain": np.where(
            np.isfinite(max_return), max_return - root, 0.0
        ),
        "log_branch_visits": np.log1p(np.maximum(visits, 0.0)),
        "branch_visited": visited,
    }
    qa = pd.DataFrame(
        {
            "run_label": windows["run_label"].astype(str),
            "prior_valid": prior_valid.astype(int),
            "terminal_actor_valid": target_valid.astype(int),
            "terminal_actor_sum_error": np.abs(np.nansum(target_raw, axis=1) - 1.0),
            "thinker_action": pd.to_numeric(windows["thinker_action"], errors="coerce"),
            "human_action": pd.to_numeric(windows["human_action"], errors="coerce"),
            "terminal_actor_argmax": np.where(target_valid, np.argmax(np.nan_to_num(target), axis=1), -1),
            "n_observed_branches": np.sum(visited, axis=1),
        }
    )
    thinker = qa["thinker_action"].fillna(-1).to_numpy(dtype=int)
    human = qa["human_action"].fillna(-1).to_numpy(dtype=int)
    row = np.arange(len(qa))
    thinker_valid = target_valid & (thinker >= 0) & (thinker < N_ACTIONS)
    human_valid = target_valid & (human >= 0) & (human < N_ACTIONS)
    qa["thinker_argmax_match"] = np.where(
        thinker_valid, qa["terminal_actor_argmax"].to_numpy(dtype=int) == thinker, np.nan
    )
    qa["thinker_chosen_probability"] = np.where(
        thinker_valid, target[row, np.clip(thinker, 0, N_ACTIONS - 1)], np.nan
    )
    qa["human_argmax_match"] = np.where(
        human_valid, qa["terminal_actor_argmax"].to_numpy(dtype=int) == human, np.nan
    )
    return features, prior, target, prior_valid & target_valid, qa


def fit_softmax_soft_targets(
    feature_matrices: Mapping[str, np.ndarray],
    target: np.ndarray,
    train_mask: np.ndarray,
    *,
    max_train: int = 60000,
) -> Optional[Dict[str, object]]:
    """Fit an action-long softmax to a probability target.

    Feature centering/scaling is learned from training rows only.  A fixed,
    evenly-spaced cap makes the 11-fold analysis tractable while preserving
    every held-out row for evaluation.
    """
    names = list(feature_matrices)
    raw = np.stack([np.asarray(feature_matrices[name], dtype=float) for name in names], axis=2)
    valid = train_mask & np.all(np.isfinite(target), axis=1)
    indices = np.flatnonzero(valid)
    if len(indices) < 500:
        return None
    if len(indices) > max_train:
        indices = indices[np.linspace(0, len(indices) - 1, max_train, dtype=int)]
    train = raw[indices].copy()
    y = target[indices]
    impute = np.zeros(train.shape[2], dtype=float)
    for column in range(train.shape[2]):
        finite = train[:, :, column][np.isfinite(train[:, :, column])]
        impute[column] = float(np.median(finite)) if len(finite) else 0.0
        train[:, :, column] = np.where(
            np.isfinite(train[:, :, column]), train[:, :, column], impute[column]
        )
    center = np.mean(train, axis=(0, 1))
    scale = np.std(train, axis=(0, 1))
    scale = np.where(scale > EPS, scale, 1.0)
    x = (train - center[None, None, :]) / scale[None, None, :]
    fixed = np.broadcast_to(
        np.eye(N_ACTIONS)[None, :, 1:], (len(indices), N_ACTIONS, N_ACTIONS - 1)
    )
    design = np.concatenate([x, fixed], axis=2)

    def objective(beta: np.ndarray):
        eta = np.einsum("nap,p->na", design, beta)
        log_p = eta - logsumexp(eta, axis=1, keepdims=True)
        p = np.exp(log_p)
        loss = -float(np.sum(y * log_p)) + 5e-5 * float(np.sum(beta[: len(names)] ** 2))
        gradient = -np.sum(np.einsum("na,nap->nap", y - p, design), axis=(0, 1))
        gradient[: len(names)] += 1e-4 * beta[: len(names)]
        return loss, gradient

    fit = minimize(objective, np.zeros(design.shape[2]), jac=True, method="L-BFGS-B")
    if not fit.success or not np.all(np.isfinite(fit.x)):
        return None
    return {
        "names": names,
        "beta": fit.x,
        "center": center,
        "scale": scale,
        "impute": impute,
        "n_train_available": int(np.sum(valid)),
        "n_train_used": int(len(indices)),
        "optimizer_iterations": int(getattr(fit, "nit", -1)),
        "optimizer_objective": float(fit.fun),
    }


def predict_softmax_model(
    fit: Mapping[str, object],
    feature_matrices: Mapping[str, np.ndarray],
    mask: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray]:
    names = list(fit["names"])
    raw = np.stack([np.asarray(feature_matrices[name], dtype=float) for name in names], axis=2)
    valid = mask.copy()
    indices = np.flatnonzero(valid)
    if len(indices) == 0:
        return indices, np.empty((0, N_ACTIONS), dtype=float)
    impute = np.asarray(fit["impute"], dtype=float)
    values = raw[indices].copy()
    for column in range(values.shape[2]):
        values[:, :, column] = np.where(
            np.isfinite(values[:, :, column]), values[:, :, column], impute[column]
        )
    center = np.asarray(fit["center"], dtype=float)
    scale = np.asarray(fit["scale"], dtype=float)
    x = (values - center[None, None, :]) / scale[None, None, :]
    fixed = np.broadcast_to(
        np.eye(N_ACTIONS)[None, :, 1:], (len(indices), N_ACTIONS, N_ACTIONS - 1)
    )
    design = np.concatenate([x, fixed], axis=2)
    eta = np.einsum("nap,p->na", design, np.asarray(fit["beta"], dtype=float))
    return indices, np.exp(eta - logsumexp(eta, axis=1, keepdims=True))


def cross_entropy_soft(target: np.ndarray, prediction: np.ndarray) -> np.ndarray:
    return -np.sum(target * np.log(np.clip(prediction, EPS, 1.0)), axis=1)


def cross_entropy_choice(choice: np.ndarray, prediction: np.ndarray) -> np.ndarray:
    valid = (choice >= 0) & (choice < N_ACTIONS)
    output = np.full(len(choice), np.nan, dtype=float)
    output[valid] = -np.log(np.clip(prediction[np.arange(len(choice))[valid], choice[valid]], EPS, 1.0))
    return output


def aggregate_directional_evidence(events: pd.DataFrame, windows: pd.DataFrame) -> pd.DataFrame:
    data = events.copy()
    data["q_revision_numeric"] = pd.to_numeric(data["root_q_revision"], errors="coerce")
    data["abs_q"] = np.abs(data["q_revision_numeric"])
    data["abs_pe"] = np.abs(pd.to_numeric(data["rollout_prediction_error"], errors="coerce"))
    aggregate = data.groupby(KEYS, sort=False, observed=True).agg(
        directional_q_sum=("directed_value_revision", "sum"),
        q_abs_sum=("abs_q", "sum"),
        directional_pe_sum=("directed_prediction_error", "sum"),
        pe_abs_sum=("abs_pe", "sum"),
        valid_revision_events=("value_revision_valid", "sum"),
        status2_events=("status2_position", "count"),
    ).reset_index()
    aggregate["directional_q_balance"] = aggregate["directional_q_sum"] / aggregate["q_abs_sum"].replace(0, np.nan)
    aggregate["directional_rollout_balance"] = aggregate["directional_pe_sum"] / aggregate["pe_abs_sum"].replace(0, np.nan)
    branch = (
        data.loc[pd.to_numeric(data["value_revision_valid"], errors="coerce").eq(1)]
        .groupby(KEYS + ["branch"], sort=False, observed=True)
        .agg(cumulative_q_revision=("q_revision_numeric", "sum"))
        .reset_index()
    )
    base = windows[KEYS].reset_index(drop=True).reset_index(names="window_index")
    branch = branch.merge(base, on=KEYS, how="left", validate="many_to_one")
    cumulative = np.zeros((len(base), N_ACTIONS), dtype=float)
    if not branch.empty:
        cumulative[branch["window_index"].to_numpy(dtype=int), branch["branch"].to_numpy(dtype=int)] = (
            branch["cumulative_q_revision"].to_numpy(dtype=float)
        )
    frame = windows.merge(aggregate, on=KEYS, how="left", validate="one_to_one")
    incumbent = pd.to_numeric(frame["incumbent_action"], errors="coerce").fillna(-1).to_numpy(dtype=int)
    competing_revision = np.full(len(frame), np.nan, dtype=float)
    competing_balance = np.full(len(frame), np.nan, dtype=float)
    valid_revision_counts = pd.to_numeric(
        frame["valid_revision_events"], errors="coerce"
    ).fillna(0).to_numpy(dtype=float)
    for index, action in enumerate(incumbent):
        if action < 0 or action >= N_ACTIONS or valid_revision_counts[index] <= 0:
            continue
        alternatives = np.arange(N_ACTIONS) != action
        denominator = float(np.sum(np.abs(cumulative[index])))
        if not np.isfinite(denominator) or denominator <= EPS:
            continue
        numerator = float(np.max(cumulative[index, alternatives]) - cumulative[index, action])
        competing_revision[index] = numerator
        competing_balance[index] = numerator / denominator
    frame["alternative_minus_incumbent_cumulative_q_revision"] = competing_revision
    frame["alternative_minus_incumbent_cumulative_q_revision_balance"] = competing_balance
    q_initial = frame[[f"root_q_initial_{a}" for a in range(N_ACTIONS)]].to_numpy(dtype=float)
    q_final = frame[[f"root_q_final_{a}" for a in range(N_ACTIONS)]].to_numpy(dtype=float)
    n_initial = frame[[f"root_n_initial_{a}" for a in range(N_ACTIONS)]].to_numpy(dtype=float)
    n_final = frame[[f"root_n_final_{a}" for a in range(N_ACTIONS)]].to_numpy(dtype=float)
    gap_initial = np.full(len(frame), np.nan)
    gap_final = np.full(len(frame), np.nan)
    for index, action in enumerate(incumbent):
        if action < 0 or action >= N_ACTIONS:
            continue
        alternatives = np.arange(N_ACTIONS) != action
        valid_i = alternatives & (n_initial[index] > 0) & np.isfinite(q_initial[index])
        valid_f = alternatives & (n_final[index] > 0) & np.isfinite(q_final[index])
        if n_initial[index, action] > 0 and valid_i.any():
            gap_initial[index] = q_initial[index, action] - np.max(q_initial[index, valid_i])
        if n_final[index, action] > 0 and valid_f.any():
            gap_final[index] = q_final[index, action] - np.max(q_final[index, valid_f])
    frame["q_gap_initial"] = gap_initial
    frame["q_gap_final"] = gap_final
    frame["q_gap_change"] = gap_final - gap_initial
    frame["q_rank_cross_direction"] = np.where(
        np.isfinite(gap_initial) & np.isfinite(gap_final),
        np.where((gap_initial >= 0) & (gap_final < 0), 1,
                 np.where((gap_initial < 0) & (gap_final >= 0), -1, 0)),
        np.nan,
    )
    incumbent_numeric = pd.to_numeric(frame["incumbent_action"], errors="coerce")
    thinker_numeric = pd.to_numeric(frame["thinker_action"], errors="coerce")
    human_numeric = pd.to_numeric(frame["human_action"], errors="coerce")
    thinker_valid = incumbent_numeric.between(0, N_ACTIONS - 1) & thinker_numeric.between(0, N_ACTIONS - 1)
    human_valid = incumbent_numeric.between(0, N_ACTIONS - 1) & human_numeric.between(0, N_ACTIONS - 1)
    frame["thinker_transition"] = np.where(
        thinker_valid, thinker_numeric.ne(incumbent_numeric).astype(float), np.nan,
    )
    frame["human_transition"] = np.where(
        human_valid, human_numeric.ne(incumbent_numeric).astype(float), np.nan,
    )
    return frame


