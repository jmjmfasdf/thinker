def group_figures(
    output: Path, effects: pd.DataFrame, inference: pd.DataFrame, dpi: int,
) -> None:
    def draw_raw_beta_heatmap(
        fig: plt.Figure,
        axis: plt.Axes,
        matrix: pd.DataFrame,
        title: str,
        *,
        rotate_columns: bool = False,
    ) -> None:
        """Draw one commensurate coefficient family on its raw-beta scale."""
        raw_values = matrix.to_numpy(dtype=float)
        finite = raw_values[np.isfinite(raw_values)]
        vmax = float(np.max(np.abs(finite))) if finite.size else 1.0
        if not np.isfinite(vmax) or vmax < EPS:
            vmax = 1.0
        cmap = plt.get_cmap("RdBu_r").copy()
        cmap.set_bad("#ECECEC")
        image = axis.imshow(
            np.ma.masked_invalid(raw_values), aspect="auto", cmap=cmap,
            vmin=-vmax, vmax=vmax,
        )
        axis.set_yticks(
            np.arange(len(matrix)),
            [f"sub{int(value):03d}" for value in matrix.index],
        )
        rotation = 45 if rotate_columns else 0
        alignment = "right" if rotate_columns else "center"
        axis.set_xticks(
            np.arange(len(matrix.columns)),
            [str(value).replace("_", " ") for value in matrix.columns],
            rotation=rotation, ha=alignment, fontsize=8,
        )
        axis.set_title(title.replace("_", " "), loc="center")
        for row in range(raw_values.shape[0]):
            for column in range(raw_values.shape[1]):
                value = raw_values[row, column]
                if np.isfinite(value):
                    text_color = "white" if abs(value) >= .62 * vmax else "#222222"
                    axis.text(column, row, f"{value:+.3g}", ha="center", va="center",
                              fontsize=8, color=text_color)
        fig.colorbar(
            image, ax=axis,
            label="Raw beta (zero-centered; panel scale)",
            shrink=.82, pad=.025,
        )

    figures = output / "figures"
    primary = effects.loc[pd.to_numeric(effects["primary_family"], errors="coerce").eq(1)].copy()
    primary["primary_id"] = primary["analysis"] + "|" + primary["effect"]
    primary_order = list(dict.fromkeys(primary["primary_id"]))

    # Primary tests have different coefficient units, so each gets its own
    # zero-centered raw-beta panel and colorbar.
    fig, axes = plt.subplots(
        1, len(primary_order),
        figsize=(max(10.5, 5.5 * len(primary_order)), 5.7),
        squeeze=False,
    )
    for column, primary_id in enumerate(primary_order):
        source = primary.loc[primary["primary_id"].eq(primary_id)]
        matrix = source.pivot_table(
            index="subject", columns="effect", values="beta", aggfunc="mean"
        )
        analysis, _ = primary_id.split("|", maxsplit=1)
        draw_raw_beta_heatmap(fig, axes[0, column], matrix, analysis)
    fig.suptitle(
        "Primary internal-control and Actor-readout tests\n"
        "Independent zero-centered raw-beta scales",
        x=.5, ha="center",
    )
    fig.tight_layout(rect=(0, 0, 1, .91))
    save_figure(fig, figures / "figure0_primary_tests.png", dpi)

    for index, scenario in enumerate(sorted(effects["scenario"].unique()), start=1):
        source = effects.loc[effects["scenario"].eq(scenario)].copy()
        analyses = list(dict.fromkeys(source["analysis"]))
        matrices: List[Tuple[str, pd.DataFrame]] = []
        panel_widths = []
        for analysis in analyses:
            analysis_source = source.loc[source["analysis"].eq(analysis)].copy()
            effect_order = list(dict.fromkeys(analysis_source["effect"]))
            matrix = analysis_source.pivot_table(
                index="subject", columns="effect", values="beta", aggfunc="mean"
            ).reindex(columns=effect_order)
            matrices.append((analysis, matrix))
            panel_widths.append(max(1.0, .72 * len(effect_order)))
        n_subjects = max(len(matrix) for _, matrix in matrices)
        fig, axes = plt.subplots(
            1, len(matrices),
            figsize=(max(8, sum(panel_widths) + 4.4 * len(matrices)),
                     max(4.2, .48 * n_subjects + 2.4)),
            squeeze=False,
            gridspec_kw={"width_ratios": panel_widths},
        )
        for panel, (analysis, matrix) in enumerate(matrices):
            draw_raw_beta_heatmap(
                fig, axes[0, panel], matrix,
                analysis if len(matrices) > 1 else scenario,
                rotate_columns=len(matrix.columns) > 2,
            )
        if len(matrices) > 1:
            fig.suptitle(
                scenario.replace("_", " ")
                + "\nIndependent zero-centered raw-beta scales by analysis",
                x=.5, ha="center",
            )
            fig.tight_layout(rect=(0, 0, 1, .90))
        else:
            fig.tight_layout()
        save_figure(fig, figures / f"figure{index}_{scenario.lower()}_group.png", dpi)


