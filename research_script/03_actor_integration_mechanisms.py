#!/usr/bin/env python3
"""Search-to-Actor integration from the read-only shared analysis cache.

The analysis has four explicitly separated targets:

1. A rollout at imaginary event ``j`` predicts whether the operation at
   ``j + 1`` continues/deepens the same path rather than resetting it. These
   outcomes are exact complements in the cached trace and are modeled once.
2. Terminal branch summaries are used to predict the status-0 *real-head*
   Actor policy after search. Leave-one-run-out cross-validation compares a
   model-prior baseline with a nested full search-evidence model.
3. The fitted Actor readout is locked and evaluated, without refitting, on
   the prerecorded human action. This is external alignment validation, not
   evidence that the human action was generated by Thinker's Actor.
4. Repeated-visit Q-update mechanics are retained as supplementary QC.

The script never creates or modifies ``outputs/00_cache``. All inferential
tables keep runs and subjects as independent units; individual imaginary
events are never treated as independent group-level evidence.

Subject mode
------------
python research_script/03_actor_integration_mechanisms.py --subject 3 --game 1

Aggregate mode (reads completed subject outputs)
------------------------------------------------
python research_script/03_actor_integration_mechanisms.py --game 1 \
    --aggregate-subjects 1,2,3,4,5,6
"""

