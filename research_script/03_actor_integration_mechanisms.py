def read_columns(path: Path, columns: Sequence[str]) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(path)
    available = pd.read_csv(path, nrows=0).columns.tolist()
    missing = [column for column in columns if column not in available]
    if missing:
        raise KeyError(f"{path} lacks required columns: {missing}")
    return pd.read_csv(path, usecols=list(columns), low_memory=False)


def standardize(series: pd.Series) -> pd.Series:
    values = pd.to_numeric(series, errors="coerce")
    scale = float(values.std(ddof=0))
    if not np.isfinite(scale) or scale < EPS:
        return pd.Series(np.zeros(len(values)), index=values.index, dtype=float)
    return (values - float(values.mean())) / scale


def scale_only(values: Sequence[float]) -> float:
    array = np.asarray(values, dtype=float)
    array = array[np.isfinite(array)]
    if len(array) == 0:
        return float("nan")
    scale = float(np.std(array, ddof=0))
    return float(np.mean(array) / scale) if scale > EPS else float("nan")


def bh_fdr(p_values: Sequence[float]) -> np.ndarray:
    p = np.asarray(p_values, dtype=float)
    q = np.full(p.shape, np.nan, dtype=float)
    valid = np.flatnonzero(np.isfinite(p))
    if len(valid) == 0:
        return q
    order = valid[np.argsort(p[valid])]
    ranked = p[order] * len(order) / np.arange(1, len(order) + 1)
    ranked = np.minimum.accumulate(ranked[::-1])[::-1]
    q[order] = np.clip(ranked, 0.0, 1.0)
    return q


def exact_sign_flip(values: Sequence[float]) -> Tuple[float, float]:
    array = np.asarray(values, dtype=float)
    array = array[np.isfinite(array)]
    if len(array) == 0:
        return float("nan"), float("nan")
    observed = abs(float(np.mean(array)))
    if len(array) <= 16:
        null = []
        for signs in itertools.product((-1.0, 1.0), repeat=len(array)):
            null.append(abs(float(np.mean(array * np.asarray(signs)))))
        p = float(np.mean(np.asarray(null) >= observed - 1e-15))
    else:
        rng = np.random.default_rng(2026)
        signs = rng.choice((-1.0, 1.0), size=(100000, len(array)))
        null = np.abs(np.mean(signs * array[None, :], axis=1))
        p = float((1 + np.sum(null >= observed)) / (len(null) + 1))
    return float(np.mean(array)), p


def inference_table(
    effects: pd.DataFrame,
    unit: str,
    include_max_t: bool,
) -> pd.DataFrame:
    if effects.empty:
        return pd.DataFrame()
    group_columns = ["scenario", "analysis", "effect", "outcome_role", "primary_family"]
    records: List[Dict[str, object]] = []
    for identifiers, source in effects.groupby(group_columns, dropna=False, sort=False):
        per_unit = source.groupby(unit, sort=False, observed=True)["beta"].mean()
        mean, p = exact_sign_flip(per_unit.to_numpy())
        records.append(
            {
                **dict(zip(group_columns, identifiers)),
                "mean_beta": mean,
                "p_sign_flip": p,
                "n_units": int(per_unit.notna().sum()),
                "unit": unit,
            }
        )
    result = pd.DataFrame(records)
    result["q_bh_within_scenario"] = np.nan
    for scenario, index in result.groupby("scenario", sort=False).groups.items():
        result.loc[index, "q_bh_within_scenario"] = bh_fdr(
            result.loc[index, "p_sign_flip"].to_numpy()
        )
    result["p_max_t"] = np.nan
    if include_max_t:
        for scenario, scenario_rows in result.groupby("scenario", sort=False):
            row_index = scenario_rows.index.to_list()
            units = sorted(effects.loc[effects["scenario"].eq(scenario), unit].unique())
            if not units or len(units) > 16:
                continue
            matrix = np.full((len(units), len(row_index)), np.nan)
            for column_index, result_index in enumerate(row_index):
                row = result.loc[result_index]
                mask = (
                    effects["scenario"].eq(row["scenario"])
                    & effects["analysis"].eq(row["analysis"])
                    & effects["effect"].eq(row["effect"])
                    & effects["outcome_role"].eq(row["outcome_role"])
                )
                values = effects.loc[mask].groupby(unit)["beta"].mean()
                for unit_index, unit_value in enumerate(units):
                    matrix[unit_index, column_index] = values.get(unit_value, np.nan)
            def studentized(values: np.ndarray) -> np.ndarray:
                n_valid = np.sum(np.isfinite(values), axis=0)
                mean = np.nanmean(values, axis=0)
                sd = np.nanstd(values, axis=0, ddof=1)
                denominator = np.divide(
                    sd,
                    np.sqrt(n_valid),
                    out=np.full_like(sd, np.nan, dtype=float),
                    where=n_valid > 1,
                )
                return np.divide(
                    mean,
                    denominator,
                    out=np.zeros_like(mean, dtype=float),
                    where=np.isfinite(denominator) & (denominator > EPS),
                )

            observed = np.abs(studentized(matrix))
            exceed = np.zeros(len(row_index), dtype=int)
            total = 0
            for signs in itertools.product((-1.0, 1.0), repeat=len(units)):
                permuted = np.abs(
                    studentized(matrix * np.asarray(signs)[:, None])
                )
                maximum = np.nanmax(permuted)
                exceed += maximum >= observed - 1e-15
                total += 1
            result.loc[row_index, "p_max_t"] = exceed / max(total, 1)
    return result


def add_joint_primary_max_t(inference: pd.DataFrame, effects: pd.DataFrame, unit: str) -> pd.DataFrame:
    """Exact synchronized max-|t| FWER for all analysis-defined primary effects."""
    inference = inference.copy()
    inference["p_joint_primary_max_t"] = np.nan
    primary = effects.loc[pd.to_numeric(effects["primary_family"], errors="coerce").eq(1)].copy()
    labels = ["scenario", "analysis", "effect", "outcome_role"]
    if primary.empty:
        return inference
    primary["primary_id"] = primary[labels].astype(str).agg("|".join, axis=1)
    per_unit = primary.groupby([unit, "primary_id"], sort=False)["beta"].mean().unstack()
    per_unit = per_unit.dropna(axis=0, how="any")
    if per_unit.empty or per_unit.shape[1] < 1 or len(per_unit) > 16:
        return inference
    matrix = per_unit.to_numpy(dtype=float)
    def t_values(values: np.ndarray) -> np.ndarray:
        mean = np.mean(values, axis=0)
        sd = np.std(values, axis=0, ddof=1)
        return np.divide(mean, sd / np.sqrt(len(values)), out=np.zeros_like(mean), where=sd > EPS)
    observed = np.abs(t_values(matrix))
    exceed = np.zeros(matrix.shape[1], dtype=int)
    total = 0
    for signs in itertools.product((-1.0, 1.0), repeat=len(matrix)):
        maximum = float(np.max(np.abs(t_values(matrix * np.asarray(signs)[:, None]))))
        exceed += maximum >= observed - 1e-15
        total += 1
    p_values = dict(zip(per_unit.columns, exceed / max(total, 1)))
    inference["primary_id"] = inference[labels].astype(str).agg("|".join, axis=1)
    mask = pd.to_numeric(inference["primary_family"], errors="coerce").eq(1)
    inference.loc[mask, "p_joint_primary_max_t"] = inference.loc[mask, "primary_id"].map(p_values)
    return inference.drop(columns="primary_id")


