def scenario2(
    windows: pd.DataFrame, events: pd.DataFrame, subject: int, game: int,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """LORO terminal Actor-policy readout and locked human validation."""
    records: List[Dict[str, object]] = []
    features, prior, target, complete, qa = make_readout_features(windows, events)
    base_names = ["log_model_prior"]
    full_names = list(features)
    run_array = windows["run_label"].astype(str).to_numpy()
    thinker = pd.to_numeric(windows["thinker_action"], errors="coerce").fillna(-1).to_numpy(dtype=int)
    human = pd.to_numeric(windows["human_action"], errors="coerce").fillna(-1).to_numpy(dtype=int)
    fold_rows: List[Dict[str, object]] = []
    for run_label in windows["run_label"].drop_duplicates():
        test = (run_array == str(run_label)) & complete
        train = (run_array != str(run_label)) & complete
        base_fit = fit_softmax_soft_targets(
            {name: features[name] for name in base_names}, target, train
        )
        full_fit = fit_softmax_soft_targets(
            {name: features[name] for name in full_names}, target, train
        )
        if base_fit is None or full_fit is None:
            continue
        base_index, base_p = predict_softmax_model(
            base_fit, {name: features[name] for name in base_names}, test
        )
        full_index, full_p = predict_softmax_model(
            full_fit, {name: features[name] for name in full_names}, test
        )
        if not np.array_equal(base_index, full_index) or len(base_index) == 0:
            continue
        index = base_index
        actor_base = cross_entropy_soft(target[index], base_p)
        actor_full = cross_entropy_soft(target[index], full_p)
        thinker_base = cross_entropy_choice(thinker[index], base_p)
        thinker_full = cross_entropy_choice(thinker[index], full_p)
        human_base = cross_entropy_choice(human[index], base_p)
        human_full = cross_entropy_choice(human[index], full_p)
        metrics = {
            "actor_policy_delta_ce": float(np.mean(actor_base - actor_full)),
            "thinker_action_delta_log_loss": float(np.nanmean(thinker_base - thinker_full)),
            "locked_human_delta_log_loss": float(np.nanmean(human_base - human_full)),
        }
        for metric, value in metrics.items():
            role = (
                "actor_internal_primary" if metric == "actor_policy_delta_ce"
                else "thinker_action_sensitivity" if metric.startswith("thinker")
                else "human_external_locked"
            )
            add_effect(
                records, windows.loc[test], subject=subject, game=game,
                run_label=str(run_label), scenario="S2_terminal_actor_readout",
                analysis="loro_full_minus_model_prior", effect=metric, beta=value,
                n_rows=len(index), outcome_role=role,
                primary_family=(metric == "actor_policy_delta_ce"),
            )
        for feature_index, feature in enumerate(full_names):
            add_effect(
                records, windows.loc[train], subject=subject, game=game,
                run_label=str(run_label), scenario="S2_terminal_actor_readout",
                analysis="terminal_branch_summary_to_actor_policy", effect=feature,
                beta=float(np.asarray(full_fit["beta"])[feature_index]),
                n_rows=int(full_fit["n_train_used"]),
                outcome_role="actor_internal_model", primary_family=False,
            )
        fold_rows.append(
            {
                "run_label": str(run_label), "n_test": int(len(index)),
                "n_train_available": int(full_fit["n_train_available"]),
                "n_train_used": int(full_fit["n_train_used"]), **metrics,
                "actor_policy_base_ce": float(np.mean(actor_base)),
                "actor_policy_full_ce": float(np.mean(actor_full)),
                "actor_policy_relative_ce_reduction": float(
                    np.mean(actor_base - actor_full) / max(np.mean(actor_base), EPS)
                ),
                "thinker_action_base_log_loss": float(np.nanmean(thinker_base)),
                "thinker_action_full_log_loss": float(np.nanmean(thinker_full)),
                "locked_human_base_log_loss": float(np.nanmean(human_base)),
                "locked_human_full_log_loss": float(np.nanmean(human_full)),
                "base_optimizer_iterations": int(base_fit["optimizer_iterations"]),
                "full_optimizer_iterations": int(full_fit["optimizer_iterations"]),
                "base_optimizer_objective": float(base_fit["optimizer_objective"]),
                "full_optimizer_objective": float(full_fit["optimizer_objective"]),
            }
        )
    if len(fold_rows) != int(windows["run_label"].nunique()):
        raise RuntimeError(
            f"LORO readout produced {len(fold_rows)} folds for "
            f"{windows['run_label'].nunique()} runs"
        )
    return pd.DataFrame(records), pd.DataFrame(fold_rows), qa


def scenario3(
    pairs: pd.DataFrame, subject: int, game: int,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """Repeated-visit update mechanics QC; not a behavioral pathway test."""
    records: List[Dict[str, object]] = []
    plotting: List[pd.DataFrame] = []
    valid_updates = pairs.loc[
        pd.to_numeric(pairs["value_revision_valid"], errors="coerce").eq(1)
    ].copy()
    mechanics = ["predicted_update_scale", "log_prior_visits", "depth", "event_progress"]
    for run_label, source in pairs.groupby("run_label", sort=False):
        update_source = valid_updates.loc[valid_updates["run_label"].eq(run_label)]
        update_betas, update_rows = fit_linear_run(
            update_source, "absolute_q_revision", mechanics, "branch"
        )
        for effect, beta in update_betas.items():
            add_effect(
                records, update_source, subject=subject, game=game, run_label=run_label,
                scenario="S3_q_update_mechanics_qc",
                analysis="prediction_error_count_decomposition_qc",
                effect=effect, beta=beta, n_rows=update_rows,
            )
        plotting.append(
            update_source[["run_label", "predicted_update_scale", "absolute_q_revision",
                           "log_prior_visits", "depth", "event_progress"]].copy()
        )
    return pd.DataFrame(records), pd.concat(plotting, ignore_index=True) if plotting else pd.DataFrame()


def quantile_summary(frame: pd.DataFrame, x: str, outcomes: Sequence[str], bins: int = 10) -> pd.DataFrame:
    records: List[Dict[str, object]] = []
    for run_label, source in frame.groupby("run_label", sort=False):
        valid = source[[x] + list(outcomes)].replace([np.inf, -np.inf], np.nan).dropna(subset=[x]).copy()
        if len(valid) < bins * 10:
            continue
        try:
            valid["bin"] = pd.qcut(valid[x], q=bins, labels=False, duplicates="drop")
        except ValueError:
            continue
        for bin_index, rows in valid.groupby("bin", sort=True):
            for outcome in outcomes:
                values = pd.to_numeric(rows[outcome], errors="coerce").dropna()
                if len(values):
                    records.append({"run_label": run_label, "bin": int(bin_index),
                                    "x_mean": float(rows[x].mean()), "outcome": outcome,
                                    "y_mean": float(values.mean()), "n": int(len(values))})
    return pd.DataFrame(records)


def draw_binned_lines(axis: plt.Axes, summary: pd.DataFrame, title: str, xlabel: str) -> None:
    colors = {name: color for name, color in zip(summary["outcome"].unique(), ("#356AA0", "#C9504D", "#4F8A5B", "#8B6FA8"))}
    for outcome, source in summary.groupby("outcome", sort=False):
        grouped = source.groupby("bin", sort=True).agg(x=("x_mean", "mean"), y=("y_mean", "mean"),
                                                       se=("y_mean", "sem")).reset_index()
        axis.plot(grouped["x"], grouped["y"], marker="o", lw=2, label=outcome.replace("_", " "), color=colors[outcome])
        axis.fill_between(grouped["x"], grouped["y"] - grouped["se"].fillna(0),
                          grouped["y"] + grouped["se"].fillna(0), color=colors[outcome], alpha=.18)
    axis.set_title(title, loc="center")
    axis.set_xlabel(xlabel)
    axis.set_ylabel("Observed probability / mean")
    axis.legend(frameon=False, fontsize=8)


def effect_bar(axis: plt.Axes, effects: pd.DataFrame, analysis: str, title: str, role: Optional[str] = None) -> None:
    source = effects.loc[effects["analysis"].eq(analysis)].copy()
    if role is not None:
        source = source.loc[source["outcome_role"].eq(role)]
    if source.empty:
        axis.text(.5, .5, "No estimable effects", ha="center", va="center", transform=axis.transAxes)
        axis.set_axis_off()
        return
    order = list(dict.fromkeys(source["effect"].tolist()))
    means = source.groupby("effect")["beta"].mean().reindex(order)
    ses = source.groupby("effect")["beta"].sem().reindex(order)
    x = np.arange(len(order))
    axis.bar(x, means, color="#555555", alpha=.82)
    axis.errorbar(x, means, yerr=ses.fillna(0), fmt="none", color="black", capsize=3)
    for xi, effect in zip(x, order):
        values = source.loc[source["effect"].eq(effect), "beta"].to_numpy(dtype=float)
        jitter = np.linspace(-.12, .12, len(values)) if len(values) > 1 else np.zeros(1)
        axis.scatter(xi + jitter, values, s=17, color="white", edgecolor="#333333", zorder=3)
    axis.axhline(0, color="#222222", lw=.8, ls="--")
    axis.set_xticks(x, [label.replace("_", " ") for label in order], rotation=30, ha="right")
    axis.set_ylabel("Run-standardized effect")
    axis.set_title(title, loc="center")


